import 'package:json_annotation/json_annotation.dart';

part 'project.g.dart';

/// Portfolio project synchronized with the Django REST Framework API.
///
/// Field names follow `ProjectSerializer` on the backend. The project URL is
/// stored in the backend's `link` field, so it is mapped explicitly.
@JsonSerializable(fieldRename: FieldRename.snake)
class Project {
  const Project({
    required this.title,
    required this.description,
    required this.techStack,
    required this.projectUrl,
    this.projectImageUrl = '',
    this.id,
  });

  factory Project.fromJson(Map<String, dynamic> json) =>
      _$ProjectFromJson(json);

  /// UUID generated by Django, so it is never sent in a POST body.
  @JsonKey(includeToJson: false)
  final String? id;

  final String title;

  final String description;

  @JsonKey(defaultValue: '')
  final String techStack;

  @JsonKey(name: 'link', defaultValue: '')
  final String projectUrl;

  @JsonKey(defaultValue: '')
  final String projectImageUrl;

  Map<String, dynamic> toJson() => _$ProjectToJson(this);
}
